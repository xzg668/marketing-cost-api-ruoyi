-- 公共联动和行情区间的财务有效价。发布事务内生成；不按OA或供货比率存储。
CREATE TABLE IF NOT EXISTS lp_finance_effective_price (
  id BIGINT NOT NULL AUTO_INCREMENT,
  business_unit_type VARCHAR(32) NOT NULL,
  org_code VARCHAR(32) NOT NULL,
  price_type VARCHAR(16) NOT NULL,
  original_id BIGINT NOT NULL,
  original_revision INT NOT NULL,
  original_month CHAR(7) NOT NULL,
  rule_identity_key CHAR(64) NOT NULL,
  rule_fingerprint CHAR(64) NOT NULL,
  material_code VARCHAR(64) NOT NULL,
  supplier_code VARCHAR(64) NOT NULL,
  supplier_name VARCHAR(255) NOT NULL,
  specification VARCHAR(512) NOT NULL,
  unit VARCHAR(64) NOT NULL,
  finance_batch_id BIGINT NOT NULL,
  finance_month CHAR(7) NOT NULL,
  scheme_code VARCHAR(64) NOT NULL,
  condition_code VARCHAR(32) NOT NULL,
  effective_from_month CHAR(7) NOT NULL,
  calculator_version VARCHAR(64) NOT NULL,
  input_fingerprint CHAR(64) NOT NULL,
  unit_price DECIMAL(38,18) NOT NULL,
  calculation_json LONGTEXT NOT NULL,
  created_at DATETIME(6) NOT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_finance_effective_input (input_fingerprint),
  KEY idx_finance_effective_read (business_unit_type, org_code, price_type, finance_batch_id, material_code),
  KEY idx_finance_effective_original (price_type, original_id, finance_batch_id),
  CONSTRAINT chk_finance_effective_type CHECK (price_type IN ('LINKED', 'RANGE')),
  CONSTRAINT chk_finance_effective_revision CHECK (original_revision > 0),
  CONSTRAINT chk_finance_effective_evidence CHECK (JSON_VALID(calculation_json))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='财务发布与原稿版本共同确定的各供应商公共有效单价';

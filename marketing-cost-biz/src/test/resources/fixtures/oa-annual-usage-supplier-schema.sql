-- Supplier dependencies for the fresh OA ingestion Testcontainers database only.
CREATE TABLE `lp_supplier_supply_ratio` (
  `id` bigint NOT NULL AUTO_INCREMENT COMMENT '主键ID',
  `business_unit_type` varchar(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci NOT NULL DEFAULT 'COMMERCIAL' COMMENT '业务单元类型',
  `material_code` varchar(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '物料代码',
  `material_name` varchar(180) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '物料名称',
  `spec_model` varchar(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '型号/规格型号',
  `unit` varchar(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '单位',
  `material_shape` varchar(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '物料形态属性',
  `supplier_name` varchar(180) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '供应商名称',
  `supplier_code` varchar(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '供应商代码，当前 Excel 可为空，后续 SRM 可补充',
  `supply_ratio` decimal(18,6) DEFAULT NULL COMMENT '供货比例，小数；NULL表示未填写',
  `effective_from` date DEFAULT NULL COMMENT '生效日期，Excel 导入阶段可为空',
  `effective_to` date DEFAULT NULL COMMENT '失效日期',
  `source_type` varchar(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci NOT NULL DEFAULT 'EXCEL' COMMENT '来源类型：EXCEL/SRM/MANUAL',
  `source_batch_no` varchar(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '来源批次号',
  `is_active` tinyint NOT NULL DEFAULT '1' COMMENT '是否当前有效：1有效，0历史失效',
  `import_file_name` varchar(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '导入文件名',
  `imported_by` varchar(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '导入人/同步人',
  `imported_at` datetime DEFAULT NULL COMMENT '导入/同步时间',
  `created_by` varchar(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '创建人',
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `updated_by` varchar(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '更新人',
  `updated_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  `deleted` tinyint NOT NULL DEFAULT '0' COMMENT '逻辑删除：0=有效，1=删除',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_supplier_ratio_batch` (`business_unit_type`,`material_code`,`source_batch_no`,`supplier_code`),
  KEY `idx_supplier_ratio_material` (`business_unit_type`,`material_code`,`material_name`,`spec_model`,`supply_ratio`),
  KEY `idx_supplier_ratio_supplier` (`business_unit_type`,`supplier_name`,`deleted`),
  KEY `idx_supplier_ratio_source` (`source_type`,`source_batch_no`),
  KEY `idx_supplier_ratio_active` (`business_unit_type`,`material_code`,`is_active`,`deleted`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='供应商供货比例主数据：用于多供应商价格命中时选择主供供应商';

CREATE TABLE `lp_supplier_price_decision` (
  `id` bigint NOT NULL AUTO_INCREMENT,
  `scope_key` char(64) NOT NULL,
  `fingerprint` char(64) NOT NULL,
  `business_unit_type` varchar(32) NOT NULL,
  `oa_no` varchar(128) NOT NULL,
  `oa_form_item_id` bigint NOT NULL,
  `period_month` varchar(7) NOT NULL,
  `pricing_date` date NOT NULL,
  `org_code` varchar(64) NOT NULL,
  `material_code` varchar(128) NOT NULL,
  `price_type` varchar(32) NOT NULL,
  `decision` varchar(32) NOT NULL COMMENT 'WAIT_IMPORT 有新增审核 / FALLBACK_HIGH 无新增审核',
  `confirmed_by` varchar(128) NOT NULL,
  `confirmed_at` datetime NOT NULL,
  `retry_status` varchar(32) NOT NULL DEFAULT 'WAITING',
  `retry_message` varchar(1000) DEFAULT NULL,
  PRIMARY KEY (`id`),
  KEY `idx_supplier_decision_scope` (`scope_key`,`id`),
  KEY `idx_supplier_decision_wait` (`business_unit_type`,`period_month`,`decision`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='通用供货比率新增审核确认记录';

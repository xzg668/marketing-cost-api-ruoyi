-- Existing range-price base table used by the public-price source reader.
-- Structure-only fixture from the isolated acceptance database; no business data.
CREATE TABLE IF NOT EXISTS `lp_price_range_item` (
  `id` bigint NOT NULL AUTO_INCREMENT,
  `business_unit_type` varchar(20) DEFAULT NULL COMMENT '业务单元',
  `org_code` varchar(32) DEFAULT NULL COMMENT '组织',
  `source_name` varchar(64) DEFAULT NULL COMMENT '来源',
  `supplier_name` varchar(128) DEFAULT NULL COMMENT '供应商名称',
  `supplier_code` varchar(64) DEFAULT NULL COMMENT '供应商代码',
  `purchase_class` varchar(64) DEFAULT NULL COMMENT '采购分类',
  `material_name` varchar(128) DEFAULT NULL COMMENT '物料名称',
  `material_code` varchar(64) NOT NULL COMMENT '物料代码',
  `spec_model` varchar(64) DEFAULT NULL COMMENT '规格型号',
  `unit` varchar(16) DEFAULT NULL COMMENT '单位',
  `formula_expr` varchar(512) DEFAULT NULL COMMENT '联动公式',
  `blank_weight` decimal(18,6) DEFAULT NULL COMMENT '下料重',
  `net_weight` decimal(18,6) DEFAULT NULL COMMENT '净重',
  `process_fee` decimal(18,6) DEFAULT NULL COMMENT '加工费',
  `agent_fee` decimal(18,6) DEFAULT NULL COMMENT '代理费',
  `range_low` decimal(18,6) NOT NULL COMMENT '区间下限',
  `range_high` decimal(18,6) NOT NULL COMMENT '区间上限',
  `range_basis` varchar(16) NOT NULL DEFAULT 'QTY' COMMENT '区间依据: QTY=数量区间 FACTOR=行情因素区间',
  `factor_rule_id` bigint DEFAULT NULL COMMENT '行情因素区间规则ID',
  `factor_code` varchar(32) DEFAULT NULL COMMENT '影响因素编码',
  `import_batch_no` varchar(64) DEFAULT NULL COMMENT '导入批次号',
  `current_flag` tinyint NOT NULL DEFAULT '1' COMMENT '是否当前版本 1=是 0=否',
  `price_excl_tax` decimal(18,6) DEFAULT NULL COMMENT '不含税价',
  `price_incl_tax` decimal(18,6) DEFAULT NULL COMMENT '含税价',
  `tax_included` tinyint NOT NULL DEFAULT '1' COMMENT '是否含税 1=含税 0=未税',
  `effective_from` date DEFAULT NULL COMMENT '生效日期',
  `effective_to` date DEFAULT NULL COMMENT '失效日期',
  `order_type` varchar(64) DEFAULT NULL COMMENT '订单类型',
  `quota` decimal(18,6) DEFAULT NULL COMMENT '配额',
  `created_at` datetime NOT NULL COMMENT '创建时间',
  `updated_at` datetime NOT NULL COMMENT '更新时间',
  PRIMARY KEY (`id`),
  KEY `idx_range_material` (`material_code`),
  KEY `idx_range_supplier` (`supplier_code`),
  KEY `idx_range_interval` (`material_code`,`range_low`,`range_high`),
  KEY `idx_price_range_but` (`business_unit_type`),
  KEY `idx_range_factor_current` (`business_unit_type`,`material_code`,`factor_code`,`current_flag`),
  KEY `idx_range_factor_rule` (`factor_rule_id`),
  KEY `idx_range_basis` (`range_basis`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='区间价表';
